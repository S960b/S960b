def main(output: str):
    path=Path(output).resolve()
    if path.exists() or path.is_symlink():
        raise SystemExit('VENDOR_OUTPUT_ALREADY_EXISTS')
    if SOURCE.is_symlink() or not SOURCE.is_file():
        raise SystemExit('REVIEWED_OAUTH_SOURCE_MISSING')
    raw=SOURCE.read_bytes()
    if hashlib.sha256(raw).hexdigest()!=EXPECTED_SHA:
        raise SystemExit('REVIEWED_OAUTH_SOURCE_SHA_MISMATCH')
    source=raw.decode('utf-8')
    tree=ast.parse(source,filename=str(SOURCE))
    selected={}
    for node in tree.body:
        if isinstance(node,(ast.FunctionDef,ast.ClassDef)) and node.name in REQUIRED:
            if node.name in selected:raise SystemExit('DUPLICATE_OAUTH_NODE')
            selected[node.name]=node
    if set(selected)!=REQUIRED:
        raise SystemExit('REQUIRED_OAUTH_DEFINITION_MISSING')
    lines=source.splitlines(keepends=True)
    pieces=[]
    for name in ('utc_iso','normalize_resource','Store','BridgeOAuthProvider','login_page'):
        n=selected[name]
        pieces.append(''.join(lines[n.lineno-1:n.end_lineno]))
    code=PREFIX+'\n\n'+'\n\n'.join(pieces)+'\n'
    ast.parse(code)
    if 'from bridge_queue import' in code or 'from git_dialog import' in code:
        raise SystemExit('GIT_OR_QUEUE_DEPENDENCY_REJECTED')
    path.parent.mkdir(parents=True,exist_ok=True,mode=0o700)
    path.write_text(code,encoding='utf-8')
    path.chmod(0o600)
    print('PINNED_OAUTH_VENDORED source_verified=true class_count=2')
    print('oauth_module_sha256='+hashlib.sha256(code.encode()).hexdigest())

if __name__=='__main__':
    if len(sys.argv)!=2:raise SystemExit('Usage: vendor_oauth.py OUTPUT_PY')
    main(sys.argv[1])
