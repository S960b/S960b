"""P31 contract helpers for the Git-dialog MCP gateway.

This module is intentionally independent of FastMCP and the P30 authority.
The production gateway should import these constants and helpers rather
than hardcoding annotations or serializing raw exceptions.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Mapping

READ_ONLY_TOOLS = frozenset({
    "dialog_list", "dialog_view", "dialog_creation_status",
    "dialog_health",
})
WRITE_TOOLS = frozenset({"dialog_append", "dialog_create"})

# dialog_create must guarantee idempotency before advertising idempotentHint.
# dialog_append is replay-safe by its unique message_id.
ANNOTATIONS: dict[str, dict[str, bool]] = {
    **{
        name: {"readOnlyHint": True, "destructiveHint": False}
        for name in READ_ONLY_TOOLS
    },
    "dialog_append": {
        "readOnlyHint": False,
        "destructiveHint": False,
        "idempotentHint": True,
    },
    "dialog_create": {
        "readOnlyHint": False,
        "destructiveHint": False,
        "idempotentHint": False,
    },
}

SAFE_CODES = frozenset({
    "wrong_turn", "head_mismatch", "peer_denied",
    "authority_unavailable", "timeout", "invalid_arguments",
    "not_found", "conflict", "internal_error",
})


@dataclass(frozen=True)
class DialogError(Exception):
    code: str
    request_id: str | None = None

    def __post_init__(self) -> None:
        if self.code not in SAFE_CODES:
            raise ValueError("unrecognized error code")


def error_result(error: BaseException, *, request_id: str | None = None) -> dict[str, Any]:
    """Produce a redacted machine-readable response; never echo exception text."""
    if isinstance(error, DialogError):
        code = error.code
        request_id = request_id or error.request_id
    elif isinstance(error, (TimeoutError,)):
        code = "timeout"
    elif isinstance(error, (ValueError, TypeError)):
        code = "invalid_arguments"
    elif isinstance(error, (ConnectionError, OSError)):
        code = "authority_unavailable"
    else:
        code = "internal_error"
    result: dict[str, Any] = {"ok": False, "code": code}
    if request_id is not None:
        # Request IDs must be generated by trusted gateway code, not client input.
        result["request_id"] = request_id
    return result


def error_from_authority(reply: Mapping[str, Any], *, request_id: str | None = None) -> dict[str, Any]:
    """Preserve only explicitly allowlisted authority codes.

    Unknown errors must not accidentally become success or leak sensitive data.
    """
    raw = reply.get("code")
    code = raw if isinstance(raw, str) and raw in SAFE_CODES else "authority_unavailable"
    result: dict[str, Any] = {"ok": False, "code": code}
    if request_id is not None:
        result["request_id"] = request_id
    return result


def tool_annotations(name: str) -> dict[str, bool]:
    """Return a defensive copy of the MCP annotations for a named tool."""
    return dict(ANNOTATIONS[name])
